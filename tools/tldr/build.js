// TL;DR: one picture and a short description per project, built from
// dusk/content (manifest.json + each project's entry.json).
//
//   npm run tldr      rewrites the Projects section of README.md
//                     and prints portfolio.pdf (one project per page)
//
// Edit the projects in their entry.json, never in README.md or here.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const CONTENT = path.join(ROOT, 'dusk', 'content');
const SITE = 'https://weymenkoo.github.io/Personal-Site/';
const START = '<!-- tldr:start (generated by npm run tldr, do not edit by hand) -->';
const END = '<!-- tldr:end -->';

function projects() {
  const { projects: slugs } = JSON.parse(fs.readFileSync(path.join(CONTENT, 'manifest.json'), 'utf8'));
  return slugs.map((slug, i) => {
    const e = JSON.parse(fs.readFileSync(path.join(CONTENT, 'projects', slug, 'entry.json'), 'utf8'));
    return {
      slug, no: 'A' + (i + 1), title: e.title, status: e.status, statusLabel: e.statusLabel,
      year: e.year, spec: e.spec, summary: e.summary,
      image: `dusk/content/projects/${slug}/${e.cover.src}`, alt: e.cover.alt,
      url: e.link ? SITE + e.link : null,
    };
  });
}

/* ---------------- README ---------------- */
function readmeSection(list) {
  const out = [START, '', '## Projects', '',
    'The short version. Each title links to the full write-up on the site. ' +
    'Printable: **[portfolio.pdf](portfolio.pdf)**.', ''];
  for (const p of list) {
    const title = p.url ? `[${p.title}](${p.url})` : p.title;
    out.push(`### ${title}`, '',
      `<img src="${p.image}" alt="${p.alt.replace(/"/g, '&quot;')}" width="720">`, '',
      `**${p.statusLabel}** · ${p.year} · ${p.spec}`, '',
      p.summary, '');
  }
  out.push(END);
  return out.join('\n');
}

function writeReadme(list) {
  const file = path.join(ROOT, 'README.md');
  const s = fs.readFileSync(file, 'utf8');
  const a = s.indexOf(START), b = s.indexOf(END);
  if (a < 0 || b < 0) throw new Error('README.md: the tldr:start / tldr:end markers are missing');
  fs.writeFileSync(file, s.slice(0, a) + readmeSection(list) + s.slice(b + END.length));
}

