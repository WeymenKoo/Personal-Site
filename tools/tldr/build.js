async function writePdf(list) {
  const { chromium } = require('@playwright/test');
  const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
  const page = await browser.newPage();
  await page.setContent(html(list), { waitUntil: 'load' });
  await page.evaluate(() => document.fonts.ready);
  await page.pdf({ path: path.join(ROOT, 'portfolio.pdf'), width: '11in', height: '8.5in', printBackground: true });
  await browser.close();
}

if (require.main === module) {
  const list = projects();
  writeReadme(list);
  writePdf(list).then(() => console.log(`README.md and portfolio.pdf: ${list.length} projects`))
    .catch(e => { console.error(e); process.exit(1); });
}

module.exports = { projects, readmeSection, html, START, END };
